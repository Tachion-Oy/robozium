test("new projects choose capabilities once and cancelled drafts are discarded", async ({ page, request }) => {
	await gotoLanding(page)
	await page.getByRole("button", { name: "New Project", exact: true }).click()
	const selector = page.getByRole("form", { name: "Capability selector" })
	const name = `Capabilities ${Date.now()}`
	await selector.getByLabel("Project name").fill(name)
	await expect(selector.getByRole("button", { name: "Launch", exact: true })).toBeEnabled()
	await selector.getByLabel("Project name").press("Enter")
	await expect(selector.getByLabel("Project name")).toHaveValue(name)
	await expect(page).not.toHaveURL(/[?&]runId=/)
	await expect(selector.getByRole("checkbox", { name: /filesystem/ })).toBeChecked()
	await expect(selector.getByRole("checkbox", { name: /filesystem/ })).toBeDisabled()
	await selector.getByRole("checkbox", { name: "mock information", exact: true }).check()
	await selector.getByRole("checkbox", { name: "mock information", exact: true }).press("Space")
	await expect(selector.getByRole("checkbox", { name: "mock information", exact: true })).not.toBeChecked()
	await selector.getByRole("checkbox", { name: "mock information", exact: true }).press("Enter")
	await expect(selector.getByRole("checkbox", { name: "mock information", exact: true })).toBeChecked()
	await selectHudView(page, "Dependencies")
	await expect(selector).toHaveCount(0)
	await selectHudView(page, "Runs Overview")
	await expect(page.getByRole("button", { name: "New Project", exact: true })).toBeVisible()
	await selectHudView(page, "Launch")
	await expect(selector.getByLabel("Project name")).toHaveValue(name)
	await expect(selector.getByRole("checkbox", { name: "mock information", exact: true })).toBeChecked()
	await selector.getByRole("button", { name: "Cancel", exact: true }).click()
	await expect(page.locator(".agent-hud__view-trigger")).toHaveText("Runs Overview")
	await page.getByRole("button", { name: "New Project", exact: true }).click()
	await expect(selector.getByLabel("Project name")).toHaveValue("")
	await expect(selector.getByRole("checkbox", { name: "mock information", exact: true })).not.toBeChecked()
	await selector.getByLabel("Project name").fill(name)
	await selector.getByRole("checkbox", { name: /mock guidance/ }).check()
	await selector.getByRole("button", { name: "Launch", exact: true }).press("Enter")
	await expect(page).toHaveURL(/[?&]runId=/)
	const runId = new URL(page.url()).searchParams.get("runId")!
	const response = await request.get(`/api/runs/${encodeURIComponent(runId)}/view`)
	expect(response.ok()).toBeTruthy()
	expect((await response.json()).capabilities).toMatchObject({ mock_information: false, mock_guidance: "on_demand" })
	await expect(page.locator(".agent-hud__textarea")).toBeVisible()
	await selectHudView(page, "Runs Overview")
	await page.getByRole("button", { name: "New Project", exact: true }).click()
	await selector.getByLabel("Project name").fill("Unsubmitted draft")
	await selector.getByRole("checkbox", { name: "mock information", exact: true }).check()
	// Escape outside the form dismisses the HUD; inside it cancels the selector.
	await page.getByRole("button", { name: "Toggle color theme", exact: true }).press("Escape")
	await expect(page.locator(".agent-hud")).toHaveClass(/agent-hud--hidden/)
	await page.getByRole("button", { name: "Expand", exact: true }).click()
	await expect(selector).toHaveCount(0)
	await page.getByRole("button", { name: "New Project", exact: true }).click()
	await expect(selector.getByLabel("Project name")).toHaveValue("")
	await expect(selector.getByRole("checkbox", { name: "mock information", exact: true })).not.toBeChecked()
})

