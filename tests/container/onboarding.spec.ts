import fs from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import { expect, test, type Page } from "@playwright/test"

const PROJECT_NAME = "Container Onboarding"
const PROJECT_SLUG = "container-onboarding"

async function openLanding(page: Page): Promise<void> {
	await page.goto("/?from=app")
	await expect(
		page.getByRole("button", { name: "New Project", exact: true }),
	).toBeVisible()
	await expect(page.getByRole("button", { name: "Mock", exact: true })).toBeVisible()
	await expect(page.getByText("OpenRouter", { exact: false })).toHaveCount(0)
	await expect(page.getByText("Cerebras", { exact: false })).toHaveCount(0)
}

async function expectGeneratedArtifact(page: Page): Promise<void> {
	await expect(
		page.locator(".agent-hud__agent", {
			hasText: "Hello! I generated a text artifact for validation:",
		}),
	).toBeVisible()

	const link = page.getByRole("link", { name: "Open the generated text file" })
	await expect(link).toBeVisible()
	const popupPromise = page.waitForEvent("popup")
	await link.click()
	const popup = await popupPromise
	await expect(popup.locator("body")).toContainText(
		"Generated by the Robozium mock agent.",
	)
	await popup.close()
}

test("folder uploads confirm real names and survive API replacement", async ({ page, request }) => {
	await openLanding(page)
	await page.getByRole("button", { name: "Runs Overview", exact: true }).click()
	await page.getByRole("option", { name: "Environment", exact: true }).click()
	const panel = page.getByRole("region", { name: "Environment settings" })
	if (process.env.ROBOZIUM_CONTAINER_PHASE === "persistence") {
		await expect(panel.getByText("container copied tool", { exact: true })).toBeVisible()
		const catalogue = await (await request.get("/api/capabilities")).json()
		expect(catalogue).toContainEqual(expect.objectContaining({ name: "container_copied_tool", selectable: true }))
		return
	}
	const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "robozium-upload-"))
	const folder = path.join(temporary, "copied_package")
	try {
		await fs.mkdir(folder)
		await fs.writeFile(path.join(folder, "env.example"), "COPIED_SETTING=example\n")
		await fs.writeFile(path.join(folder, "__init__.py"), "from roboz.deployment import Capability, ToolLabel\nfrom roboz.tools import stop\nCAPABILITY = Capability(label=ToolLabel('container_copied_tool', selectable=True), value=stop)\n")
		await panel.getByLabel("Choose tool or skill folder").setInputFiles(folder)
		await expect(page.getByText("Tool container_copied_tool found and imported. Available after restart.", { exact: true })).toBeVisible()
		await expect(panel.getByText("container copied tool", { exact: true })).toBeVisible()
		await expect(panel.getByLabel("Current value for COPIED_SETTING")).toHaveText("example")
	} finally {
		await fs.rm(temporary, { recursive: true, force: true })
	}
})

test("a fresh clone completes the first-use browser journey", async ({ page }) => {
	test.skip(
		process.env.ROBOZIUM_CONTAINER_PHASE === "persistence",
		"persistence phase selected",
	)

	await openLanding(page)
	await page.getByRole("button", { name: "New Project", exact: true }).click()
	await page.getByLabel("Project name").fill(PROJECT_NAME)
	await page.getByRole("form", { name: "Capability selector" }).getByRole("button", { name: "Launch", exact: true }).click()
	await expect(page).toHaveURL(/[?&]runId=/)

	await expectGeneratedArtifact(page)
	const textarea = page.locator(".agent-hud__textarea")
	await textarea.fill("first container reply")
	await page.getByRole("button", { name: "Send", exact: true }).click()
	await expect(
		page.locator(".agent-hud__agent", {
			hasText: "Thanks. One more thing before I finish?",
		}),
	).toBeVisible()

	await textarea.fill("second container reply")
	await page.getByRole("button", { name: "Send", exact: true }).click()
	await expect.poll(() => new URL(page.url()).searchParams.get("runId")).toBeNull()
	await expect(
		page.getByRole("button", { name: `Open ${PROJECT_SLUG}`, exact: true }),
	).toBeVisible()
})

test("the first-use project survives API replacement", async ({ page }) => {
	test.skip(
		process.env.ROBOZIUM_CONTAINER_PHASE !== "persistence",
		"onboarding phase selected",
	)

	await openLanding(page)
	await page
		.getByRole("button", { name: `Open ${PROJECT_SLUG}`, exact: true })
		.click()
	await page.getByRole("form", { name: "Capability selector" })
		.getByRole("button", { name: "Launch", exact: true }).click()
	await expect(page).toHaveURL(/[?&]runId=/)
	await expectGeneratedArtifact(page)
})
